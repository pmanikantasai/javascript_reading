// do while loop
// do while loop is similar to while loop but it will execute the block of code at least once before checking the condition

let j =10 // here j is greater than 10 but the do while loop will execute the block of code at least once before checking the condition
do {
   // console.log(j)
    j++
} while (j<10)  // this will print 10 once and then exit the loop because j is greater than 10

